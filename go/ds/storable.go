package ds

// Storable - интерфейс всех структур данных проекта (аналог IStorable из C++).
// Каждая структура называет свой тип, сообщает размер, отдает элементы списком строк (Dump),
// восстанавливается из такого списка (Load) и рисует себя для вывода (Show).
// На этом построены сериализация и фабрика: они работают с любой структурой через интерфейс.
type Storable interface {
	Type() byte                 // буква типа: M F L S Q T H
	Size() int                  // число элементов
	Dump() []string             // элементы в порядке хранения
	Load(tokens []string) error // восстановление из элементов
	Show() string               // текст для вывода на экран
}
